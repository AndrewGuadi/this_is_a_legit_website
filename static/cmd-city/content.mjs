export const capacity = (t) => {
  const d = TOOLS[t.type];
  return d?.capacity && [...ZONES, "tower"].includes(t.type)
    ? d.capacity * [1, 2.5, 6][t.level - 1]
    : d?.capacity || 0;
};
export const money = (n) =>
  new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(n / 100);
